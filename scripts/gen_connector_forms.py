"""Write web/src/features/sources/connectors.generated.ts from docs/contracts/connectors.yaml.

The admin UI renders each connector kind's settings form from these schemas (connectors.yaml:
"the admin UI renders forms from these schemas"). Run ``make connectors`` after changing the
contract; ``api/tests/unit/test_connector_forms.py`` fails while the file is stale.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
CONTRACT = ROOT / "docs" / "contracts" / "connectors.yaml"
OUTPUT = ROOT / "web" / "src" / "features" / "sources" / "connectors.generated.ts"
HEADER = (
    "// GENERATED by scripts/gen_connector_forms.py from docs/contracts/connectors.yaml;\n"
    "// do not edit by hand. Run `make connectors` after changing the contract.\n"
)


def _clean(value: object) -> object:
    """Drop keys whose value is null. In the contract's flow mappings an unquoted comma inside a
    description splits it into bogus keys such as ``counters: null`` (sources UI review 3;
    quoting is proposed as CP-12); a real schema never has a null-valued keyword."""
    if isinstance(value, dict):
        return {k: _clean(v) for k, v in value.items() if v is not None}
    if isinstance(value, list):
        return [_clean(v) for v in value]
    return value


def render() -> str:
    contract = yaml.safe_load(CONTRACT.read_text(encoding="utf-8"))
    kinds = {k: v for k, v in contract.items() if isinstance(v, dict) and "config" in v}
    rules = contract["common_extraction_rules"]
    payload = _clean({"kinds": {k: v["config"] for k, v in kinds.items()},
                      "extraction_rules": rules})  # fmt: skip
    body = json.dumps(payload, indent=2, sort_keys=True)
    return HEADER + f"export const CONNECTORS = {body} as const;\n"


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        return 0 if OUTPUT.exists() and OUTPUT.read_text(encoding="utf-8") == text else 1
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
