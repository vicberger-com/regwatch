#!/usr/bin/env python3
"""Generate api/seed/jurisdictions.yaml and api/seed/control_framework.yaml (#28).

Development tool, standard library only. It reads local copies of the inputs below and makes
no network requests. Fetch them, then run from the repository root:

    I18N=55c3a72603faf0185661e80841074e1c2fcf8db5   # i18n-iso-countries v7.14.0 (MIT)
    NE=v5.1.2                                        # Natural Earth (public domain)
    OSCAL=f0de6d8d8c059d374f15e0ae07508d82e370fc1d   # NIST OSCAL content (CC0-1.0)
    curl -sSLO https://raw.githubusercontent.com/michaelwittig/node-i18n-iso-countries/$I18N/langs/en.json
    curl -sSLO https://raw.githubusercontent.com/michaelwittig/node-i18n-iso-countries/$I18N/codes.json
    curl -sSLO https://raw.githubusercontent.com/nvkelso/natural-earth-vector/$NE/geojson/ne_50m_admin_0_countries.geojson
    curl -sSLO https://raw.githubusercontent.com/usnistgov/oscal-content/$OSCAL/src/nist.gov/CSF/v2.0/xml/NIST_CSF_v2.0_catalog.xml
    curl -sSL -o m49.html https://unstats.un.org/unsd/methodology/m49/overview/
    python3 -I scripts/build_seed.py <directory holding those five files>

The pinned files are checked against their SHA-256; the M49 page is live, so its hash is only
recorded in the output header.
"""

from __future__ import annotations

import hashlib
import html
import json
import re
import sys
import xml.etree.ElementTree as ET  # noqa: S405 - pinned, hash-checked NIST file
from pathlib import Path

PINNED = {
    "en.json": "7445185d6424e574027a7cd14029e000784eaa03a2b83ab097742079f701e702",
    "codes.json": "736d7666e943e0bca25c518e3903e2b328ce54b94662553a6472c379dbfb50aa",
    "ne_50m_admin_0_countries.geojson": (
        "3e458fc036ad0a66411f2c1e6cac49c5d7bfb81cb1123bc513b22511a2b7fdeb"
    ),
    "NIST_CSF_v2.0_catalog.xml": (
        "f0b2a3f67dc9fc78abc978d69c114a30b2d1681f3a81aa6497b140ea8dc21c42"
    ),
}
SUPRANATIONAL = [
    ("EU", "European Union"),
    ("COE", "Council of Europe"),
    ("OECD", "Organisation for Economic Co-operation and Development"),
    ("UN", "United Nations"),
    ("INTL", "International"),
]
# Codes the M49 table does not list; geographic sub-region assigned (ASSUMPTIONS.md, #28).
REGION_OVERRIDES = {"TW": "030", "XK": "039"}
OSCAL_NS = {"o": "http://csrc.nist.gov/ns/oscal/1.0"}
OUT = Path(__file__).resolve().parent.parent / "api" / "seed"


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def q(value: str) -> str:
    """YAML double-quoted scalar (JSON strings are valid YAML)."""
    return json.dumps(value, ensure_ascii=False)


def m49_subregions(page: Path) -> dict[str, str]:
    """ISO alpha-2 -> M49 sub-region code, from the English download table."""
    text = page.read_text(encoding="utf-8")
    start = text.index('id = "downloadTableEN"')
    table = text[start : text.index("</table>", start)]
    out = {}
    for row in re.findall(r"<tr.*?</tr>", table, flags=re.S)[1:]:
        cells = [
            html.unescape(re.sub(r"<[^>]+>", "", c)).strip()
            for c in re.findall(r"<td[^>]*>(.*?)</td>", row, flags=re.S)
        ]
        if cells and cells[10] and cells[4]:
            out[cells[10]] = cells[4]
    return out


def geometry_refs(geojson: Path, alpha3: dict[str, str]) -> dict[str, str]:
    """ISO alpha-2 -> Natural Earth ADM0_A3 (ADR-0004 decision 4).

    Where several features share an ISO_A2_EH code (AU: AUS, IOA, ATC), the feature whose
    ADM0_A3 equals the ISO alpha-3 code is the jurisdiction's own geometry.
    """
    features: dict[str, list[str]] = {}
    for feature in json.loads(geojson.read_text(encoding="utf-8"))["features"]:
        props = feature["properties"]
        if props["ISO_A2_EH"] != "-99":
            features.setdefault(props["ISO_A2_EH"], []).append(props["ADM0_A3"])
    out = {}
    for code, refs in features.items():
        own = [r for r in refs if r == alpha3.get(code)]
        if len(refs) == 1 or own:
            out[code] = own[0] if own else refs[0]
        else:
            raise SystemExit(f"ambiguous geometry for {code}: {refs}")
    return out


def jurisdictions(src: Path) -> str:
    names = json.loads((src / "en.json").read_text(encoding="utf-8"))["countries"]
    codes = json.loads((src / "codes.json").read_text(encoding="utf-8"))
    alpha3 = {c[0]: c[1] for c in codes}
    regions = m49_subregions(src / "m49.html") | REGION_OVERRIDES
    geoms = geometry_refs(src / "ne_50m_admin_0_countries.geojson", alpha3)
    lines = [
        "# GENERATED by scripts/build_seed.py; do not edit by hand.",
        "# code, name: i18n-iso-countries v7.14.0 (MIT), commit 55c3a72, en.json "
        "(first name = the library's official name); XK is user-assigned.",
        "# region_code: UN M49 sub-region, UNSD 'Standard country or area codes for statistical",
        f"#   use (M49)' overview page, read 2026-11-02, sha256 {sha256(src / 'm49.html')};",
        "#   TW and XK are not in M49 and use REGION_OVERRIDES in the script.",
        "# geometry_ref: Natural Earth v5.1.2 (public domain, f1890d9) "
        "ne_50m_admin_0_countries ADM0_A3; null = no polygon of its own (ADR-0004).",
        "jurisdictions:",
    ]
    for code in sorted(names):
        name = names[code][0] if isinstance(names[code], list) else names[code]
        region = regions.get(code)
        geom = geoms.get(code)
        lines.append(
            f"  - {{ code: {q(code)}, name: {q(name)}, kind: country, "
            f"region_code: {q(region) if region else 'null'}, "
            f"geometry_ref: {q(geom) if geom else 'null'} }}"
        )
    for code, name in SUPRANATIONAL:
        lines.append(f"  - {{ code: {q(code)}, name: {q(name)}, kind: supranational }}")
    return "\n".join(lines) + "\n"


def control_framework(src: Path) -> str:
    root = ET.parse(src / "NIST_CSF_v2.0_catalog.xml").getroot()  # noqa: S314
    version = root.findtext("o:metadata/o:version", namespaces=OSCAL_NS)
    lines = [
        "# GENERATED by scripts/build_seed.py; do not edit by hand.",
        "# Source: NIST CSF 2.0 OSCAL catalog (catalog version "
        f"{version}), usnistgov/oscal-content commit",
        "#   f0de6d8d8c059d374f15e0ae07508d82e370fc1d, "
        "src/nist.gov/CSF/v2.0/xml/NIST_CSF_v2.0_catalog.xml.",
        "# License: public domain in the US and CC0-1.0 worldwide (LICENSE.md at that commit).",
        "# Functions and active categories; entries with status=withdrawn are left out (BL-21).",
        "# Term keys are the OSCAL ids in lower case with '.' as '-'; the id itself is a synonym.",
        "facets:",
        "  - key: control_framework",
        "    label: Control framework",
        "    sort_order: 50",
        "    terms:",
    ]
    for group in root.findall("o:group", OSCAL_NS):
        gid, title = group.get("id", ""), group.findtext("o:title", namespaces=OSCAL_NS) or ""
        lines.append(
            f"      - {{ key: {q(gid.lower())}, label: {q(f'{gid} {title.title()}')}, "
            f"synonyms: [{q(gid)}] }}"
        )
        for control in group.findall("o:control", OSCAL_NS):
            withdrawn = any(
                p.get("name") == "status" and p.get("value") == "withdrawn"
                for p in control.findall("o:prop", OSCAL_NS)
            )
            if withdrawn:
                continue
            cid = control.get("id", "")
            ctitle = control.findtext("o:title", namespaces=OSCAL_NS) or ""
            lines.append(
                f"      - {{ key: {q(cid.lower().replace('.', '-'))}, "
                f"label: {q(f'{cid} {ctitle}')}, parent: {q(gid.lower())}, synonyms: [{q(cid)}] }}"
            )
    return "\n".join(lines) + "\n"


def main() -> None:
    src = Path(sys.argv[1])
    for name, expected in PINNED.items():
        if sha256(src / name) != expected:
            raise SystemExit(f"{name}: SHA-256 mismatch; fetch the pinned version")
    (OUT / "jurisdictions.yaml").write_text(jurisdictions(src), encoding="utf-8")
    (OUT / "control_framework.yaml").write_text(control_framework(src), encoding="utf-8")


if __name__ == "__main__":
    main()
