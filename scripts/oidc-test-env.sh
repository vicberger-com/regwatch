#!/usr/bin/env bash
# Create the env files of the `oidc-test` profile (BL-147; development and QA only): a Keycloak
# with the `regwatch` realm (deploy/oidc-test/regwatch-realm.json), on 127.0.0.1:8190 only.
#   deploy/oidc-test.env  read by api: the issuer, the client and REGWATCH_OIDC_TEST_PROVIDER.
#   deploy/keycloak.env   read by keycloak only: its bootstrap administrator, the client secret,
#                         the redirect URI and the test users' password.
#   deploy/oidc-test-e2e.env  the test users' password only, for the e2e journey (E2E_OIDC_ENV).
# Usage: scripts/oidc-test-env.sh [base URL, default http://localhost] [--force]
# Fresh random secrets, owner-only files, never printed. Never commit the results.
set -euo pipefail
umask 077
root="$(cd "$(dirname "$0")/.." && pwd)"
base="${1:-http://localhost}"
base="${base%/}"
api_env="$root/deploy/oidc-test.env"
kc_env="$root/deploy/keycloak.env"
e2e_env="$root/deploy/oidc-test-e2e.env"
if [[ "${2:-}" != "--force" && -f "$api_env" && -f "$kc_env" ]]; then
  echo "deploy/oidc-test.env and deploy/keycloak.env exist; pass --force to replace them"
  exit 0
fi
rand() { od -An -tx1 -N"$1" /dev/urandom | tr -d ' \n'; }
secret="$(rand 32)"
user_password="$(rand 16)"
{
  echo "# Generated by scripts/oidc-test-env.sh (the oidc-test profile, dev and QA only). Never commit."
  echo "REGWATCH_OIDC_ISSUER=http://idp.localhost:8190/realms/regwatch"
  echo "REGWATCH_OIDC_CLIENT_ID=regwatch"
  echo "REGWATCH_OIDC_CLIENT_SECRET=$secret"
  echo "REGWATCH_OIDC_TEST_PROVIDER=true"
} > "$api_env"
{
  echo "# Generated by scripts/oidc-test-env.sh (the oidc-test profile, dev and QA only). Never commit."
  echo "KC_BOOTSTRAP_ADMIN_USERNAME=admin"
  echo "KC_BOOTSTRAP_ADMIN_PASSWORD=$(rand 24)"
  echo "KC_CLIENT_SECRET=$secret"
  echo "KC_REDIRECT_URI=$base/api/v1/auth/oidc/callback"
  echo "KC_USER_PASSWORD=$user_password"
} > "$kc_env"
{
  echo "# Generated by scripts/oidc-test-env.sh: the oidc-test users' password, for e2e. Never commit."
  echo "KC_USER_PASSWORD=$user_password"
} > "$e2e_env"
chmod 600 "$api_env" "$kc_env" "$e2e_env"
echo "wrote deploy/oidc-test.env, deploy/keycloak.env and deploy/oidc-test-e2e.env for $base"
