#!/usr/bin/env bash
# Create deploy/.env, deploy/db.env and deploy/queue.env for local development from
# docs/contracts/env.example.
# Fills required values with safe local ones and fresh random secrets. Never commit the results.
#   deploy/.env     the application's settings; read by api, worker, beat and web. It holds the
#                   regwatch_api login only.
#   deploy/db.env   the owner password, the regwatch_api password and the owner URL for
#                   migrations; read only by the db container and the one-off migrate container,
#                   so long-running app containers never hold owner credentials (BL-61).
#   deploy/queue.env the Valkey password; read only by the queue container, which builds its ACL
#                   from it. The app containers get it inside REGWATCH_QUEUE_URL (BL-90 (a)).
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
target="$root/deploy/.env"
dbtarget="$root/deploy/db.env"
queuetarget="$root/deploy/queue.env"

write_queue_env() {
  {
    echo "# Generated by scripts/dev-env.sh for local development. Never commit."
    echo "# The Valkey password: the queue container only (BL-90 (a))."
    echo "VALKEY_PASSWORD=$1"
  } > "$queuetarget"
  chmod 600 "$queuetarget"
}

if [[ "${1:-}" != "--force" && -f "$target" && -f "$dbtarget" && ! -f "$queuetarget" ]]; then
  # A setup from before the queue password: add one, and change only the queue URL line, so the
  # secret key and the database passwords are kept.
  queuepass="$(od -An -tx1 -N24 /dev/urandom | tr -d ' \n')"
  write_queue_env "$queuepass"
  sed -i.bak -E "s|^REGWATCH_QUEUE_URL=.*|REGWATCH_QUEUE_URL=valkey://regwatch:$queuepass@queue:6379/0|" "$target"
  rm -f "$target.bak"
  echo "wrote deploy/queue.env and set the queue URL in deploy/.env; restart the stack"
  exit 0
fi
if [[ "${1:-}" != "--force" ]]; then
  if [[ -f "$target" && -f "$dbtarget" ]]; then
    echo "deploy/.env and deploy/db.env exist; pass --force to recreate them"
    exit 0
  fi
  if [[ -f "$target" ]]; then
    # An older deploy/.env without db.env: new passwords would not match the existing volume.
    echo "deploy/.env predates deploy/db.env (BL-61); see deploy/README.md, then run" >&2
    echo "scripts/dev-env.sh --force and docker volume rm regwatch_pgdata" >&2
    exit 1
  fi
fi
secret="$(od -An -tx1 -N32 /dev/urandom | tr -d ' \n')"
dbpass="$(od -An -tx1 -N16 /dev/urandom | tr -d ' \n')"
apppass="$(od -An -tx1 -N16 /dev/urandom | tr -d ' \n')"
queuepass="$(od -An -tx1 -N24 /dev/urandom | tr -d ' \n')"
{
  echo "# Generated by scripts/dev-env.sh for local development. Never commit."
  # Strip inline comments, then fill the development values.
  sed -E -e 's/[[:space:]]+#.*$//' -e '/^#/d' -e '/^$/d' "$root/docs/contracts/env.example" \
    | sed -E \
      -e "/^REGWATCH_MIGRATION_DATABASE_URL=/d" \
      -e "s|^REGWATCH_SECRET_KEY=.*|REGWATCH_SECRET_KEY=$secret|" \
      -e "s|^REGWATCH_DATABASE_URL=.*|REGWATCH_DATABASE_URL=postgresql+psycopg://regwatch_api:$apppass@db:5432/regwatch|" \
      -e "s|^REGWATCH_QUEUE_URL=.*|REGWATCH_QUEUE_URL=valkey://regwatch:$queuepass@queue:6379/0|" \
      -e "s|^REGWATCH_BASE_URL=.*|REGWATCH_BASE_URL=http://localhost|" \
      -e "s|^REGWATCH_TRUSTED_PROXIES=.*|REGWATCH_TRUSTED_PROXIES=10.89.0.2/32|"
} > "$target"
{
  echo "# Generated by scripts/dev-env.sh for local development. Never commit."
  echo "# Owner credentials: the db and migrate containers only (BL-61)."
  echo "POSTGRES_PASSWORD=$dbpass"
  echo "POSTGRES_APP_PASSWORD=$apppass"
  echo "REGWATCH_MIGRATION_DATABASE_URL=postgresql+psycopg://regwatch:$dbpass@db:5432/regwatch"
} > "$dbtarget"
write_queue_env "$queuepass"
chmod 600 "$target" "$dbtarget"
echo "wrote deploy/.env, deploy/db.env and deploy/queue.env"
