"""SQLAlchemy models. Tables come from docs/contracts/schema.sql (migration 0001, #28).

M4 owns ``item``, ``item_version`` and ``change_event``. ``item_term`` and ``item_jurisdiction``
are M2's models (taxonomy owns them for merges and usage counts); M4 writes them, and they are
re-exported here.
``item.search_vector`` is generated by the database and never written here.
"""

from __future__ import annotations

import uuid
from datetime import datetime
from decimal import Decimal
from typing import Any

from sqlalchemy import Computed, ForeignKey, text
from sqlalchemy.dialects.postgresql import JSONB, TSVECTOR
from sqlalchemy.orm import Mapped, mapped_column

from regwatch.core.db import Base
from regwatch.taxonomy.models import ItemJurisdiction, ItemTerm

__all__ = ["ChangeEvent", "Item", "ItemJurisdiction", "ItemTerm", "ItemVersion"]


class Item(Base):
    __tablename__ = "item"

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, server_default=text("uuidv7()"))
    created_at: Mapped[datetime] = mapped_column(server_default=text("now()"))
    updated_at: Mapped[datetime] = mapped_column(server_default=text("now()"))
    source_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("source.id"))
    canonical_url: Mapped[str]
    url_hash: Mapped[str] = mapped_column(unique=True)
    external_id: Mapped[str | None]
    title: Mapped[str]
    title_en: Mapped[str | None]
    summary: Mapped[str | None]
    summary_en: Mapped[str | None]
    language: Mapped[str | None]
    published_at: Mapped[datetime | None]
    discovered_at: Mapped[datetime] = mapped_column(server_default=text("now()"))
    last_changed_at: Mapped[datetime] = mapped_column(server_default=text("now()"))
    content_hash: Mapped[str]
    fetched_host: Mapped[str | None]  # CP-19: None when only listed, never fetched
    status: Mapped[str] = mapped_column(server_default=text("'new'"))
    needs_review: Mapped[bool] = mapped_column(server_default=text("false"))
    translation_pending: Mapped[bool] = mapped_column(server_default=text("false"))
    current_version_no: Mapped[int] = mapped_column(server_default=text("1"))
    regulation_id: Mapped[uuid.UUID | None]  # the regulation table has no model yet
    attributes: Mapped[dict[str, Any]] = mapped_column(JSONB, server_default=text("'{}'::jsonb"))
    search_vector: Mapped[Any] = mapped_column(
        TSVECTOR, Computed("search_vector", persisted=True), deferred=True
    )
    # CP-21 (migration 0007): title and summary in the item's own language's configuration
    search_vector_stemmed: Mapped[Any] = mapped_column(
        TSVECTOR, Computed("search_vector_stemmed", persisted=True), deferred=True
    )


class ItemVersion(Base):
    __tablename__ = "item_version"

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, server_default=text("uuidv7()"))
    created_at: Mapped[datetime] = mapped_column(server_default=text("now()"))
    item_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("item.id", ondelete="CASCADE"))
    run_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("capture_run.id"))
    version_no: Mapped[int]
    content_text: Mapped[str]
    content_html_ref: Mapped[str | None]
    content_hash: Mapped[str]
    diff_from_previous: Mapped[str | None]
    changed_pct: Mapped[Decimal | None]
    translations: Mapped[dict[str, Any]] = mapped_column(JSONB, server_default=text("'{}'::jsonb"))


class ChangeEvent(Base):
    __tablename__ = "change_event"

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, server_default=text("uuidv7()"))
    created_at: Mapped[datetime] = mapped_column(server_default=text("now()"))
    item_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("item.id", ondelete="CASCADE"))
    jurisdiction_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("jurisdiction.id"))
    kind: Mapped[str]
    occurred_at: Mapped[datetime] = mapped_column(server_default=text("now()"))
    severity: Mapped[str] = mapped_column(server_default=text("'info'"))
    summary: Mapped[str | None]
    acknowledged_by: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("user.id"))
    acknowledged_at: Mapped[datetime | None]
